// ---- Signed Session Tokens (Phase 1) ----
// Separate from the TLS identity above: this is GmailServer's own RSA
// keypair, used ONLY to sign session tokens. Generated once at startup if
// missing (same pattern KeyServer already uses for its own
// keyserver_private.pem/keyserver_public.pem). KeyServer and RecoveryServer
// load gmailserver_public.pem (read-only on their side) to verify tokens;
// neither server ever generates this keypair - only GmailServer does.
#define GMAIL_SIGNING_KEY_SIZE 2048
#define GMAIL_SIGNING_PRIVATE_KEY_PATH "gmailserver_private.pem"
#define GMAIL_SIGNING_PUBLIC_KEY_PATH  "gmailserver_public.pem"

